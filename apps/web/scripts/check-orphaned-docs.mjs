#!/usr/bin/env node
// Fails when a docs page is unreachable from `sidebars.ts`, in either
// direction, or when a public component has no docs page at all:
//
//   orphaned — the .md/.mdx file exists but no sidebar entry points at it, so
//              the page builds and is served but appears in no navigation.
//              Only someone typing the URL would ever find it. Docusaurus does
//              not warn about this, which is how ui-kit#347's CodeEditor page
//              stayed invisible until ui-kit#352 noticed by hand.
//
//   dangling — a sidebar entry names a document id with no matching file.
//              Docusaurus does fail the build on this one, but catching it here
//              reports it next to the orphan check, in a fraction of the time a
//              full docs build takes.
//
//   missing  — a component exported from a packages/ui tier index has no
//              docs/components/<tier>/<file>.mdx. The other two checks only
//              compare docs/ with sidebars.ts, so a component that never got a
//              page passed both (ui-kit#543: Tooltip and Tabs).
//
// This sidebar is fully manual (no `autogenerated` item — see the comment at the
// top of sidebars.ts), so nothing else keeps the two lists in step.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const WEB_DIR = path.join(__dirname, '..');
const DOCS_DIR = path.join(WEB_DIR, 'docs');
const SIDEBARS_FILE = path.join(WEB_DIR, 'sidebars.ts');
const COMPONENTS_DIR = path.join(
  WEB_DIR,
  '..',
  '..',
  'packages',
  'ui',
  'src',
  'components',
);
const TIERS = ['atoms', 'molecules', 'organisms', 'templates'];

/**
 * `sidebars.ts` is plain data apart from a type-only import and a single type
 * annotation. Strip those two and the file is valid ESM, so we can import it and
 * walk the real object.
 *
 * Deliberately not a regex over the source: quotes appear in comments and in
 * `label:` values too, and a naive `/'([^']+)'/g` sweep reports the category
 * labels ('General', 'Data Entry', …) plus fragments of prose as document ids —
 * 10 false positives on this file when tried. Letting the JS parser do the work
 * removes that whole class of error.
 */
const loadSidebars = async () => {
  const source = fs
    .readFileSync(SIDEBARS_FILE, 'utf8')
    .replace(/^\s*import\s+type\s[^;]*;\s*$/gm, '')
    .replace(/:\s*SidebarsConfig\b/g, '');

  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ui-kit-sidebars-'));
  const file = path.join(dir, 'sidebars.mjs');

  try {
    fs.writeFileSync(file, source);
    return (await import(pathToFileURL(file).href)).default;
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
};

/**
 * Collect every document id the sidebar points at. Handles the shorthand string
 * form, `{ type: 'doc' }`, `{ type: 'category' }` (including a category whose
 * own `link` targets a doc), and arbitrary nesting. Entries that don't name a
 * local document — `link`/`href`, `autogenerated`, `ref` — are skipped, since
 * there is no file for them to match.
 */
const collectReferencedIds = sidebars => {
  const ids = new Set();

  const walk = node => {
    if (typeof node === 'string') {
      ids.add(node);
      return;
    }

    if (Array.isArray(node)) {
      node.forEach(walk);
      return;
    }

    if (!node || typeof node !== 'object') {
      return;
    }

    if (node.type === 'doc' && typeof node.id === 'string') {
      ids.add(node.id);
    }

    // A category can carry its own landing doc: `link: { type: 'doc', id }`.
    if (node.link?.type === 'doc' && typeof node.link.id === 'string') {
      ids.add(node.link.id);
    }

    if (node.items) {
      walk(node.items);
    }
  };

  walk(Object.values(sidebars));

  return ids;
};

/** Every .md/.mdx page under docs/, as the document ids Docusaurus derives. */
const listDocumentIds = (dir, ids = []) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      listDocumentIds(full, ids);
    } else if (/\.mdx?$/.test(entry.name)) {
      // Docusaurus ids are posix-style and extension-less, relative to docs/.
      ids.push(
        path
          .relative(DOCS_DIR, full)
          .split(path.sep)
          .join('/')
          .replace(/\.mdx?$/, ''),
      );
    }
  }

  return ids;
};

/**
 * The doc id each public component should have: `components/<tier>/<file>`,
 * one per value export (`export { default as X } from './x'`, or named exports
 * such as `export { Row, Col } from './grid'`) in a tier's index.ts. Type-only
 * exports are skipped. Subpath-only components such as CodeEditor are not in a
 * tier index, so they are not required here.
 */
const listComponentDocIds = () =>
  TIERS.flatMap(tier => {
    const source = fs.readFileSync(
      path.join(COMPONENTS_DIR, tier, 'index.ts'),
      'utf8',
    );

    return [...source.matchAll(/^export \{[^}]*\} from '\.\/([^']+)';/gm)].map(
      ([, file]) => `components/${tier}/${file}`,
    );
  });

const sidebars = await loadSidebars();
const referenced = collectReferencedIds(sidebars);
const documents = listDocumentIds(DOCS_DIR);

const orphaned = documents.filter(id => !referenced.has(id)).sort();
const dangling = [...referenced].filter(id => !documents.includes(id)).sort();
const missing = [...new Set(listComponentDocIds())]
  .filter(id => !documents.includes(id))
  .sort();

if (orphaned.length > 0 || dangling.length > 0 || missing.length > 0) {
  if (orphaned.length > 0) {
    console.error(
      `\n✗ ${orphaned.length} docs page(s) exist but no sidebar entry points at them:\n`,
    );
    for (const id of orphaned) {
      console.error(`    ${id}`);
    }
    console.error(
      `\n  They build and are served, but appear in no navigation — add each to`,
    );
    console.error(`  apps/web/sidebars.ts under the matching category.`);
  }

  if (dangling.length > 0) {
    console.error(
      `\n✗ ${dangling.length} sidebar entr(ies) name a document that does not exist:\n`,
    );
    for (const id of dangling) {
      console.error(`    ${id}`);
    }
    console.error(
      `\n  Create apps/web/docs/<id>.mdx or remove the entry from sidebars.ts.`,
    );
  }

  if (missing.length > 0) {
    console.error(
      `\n✗ ${missing.length} public component(s) have no docs page:\n`,
    );
    for (const id of missing) {
      console.error(`    ${id}`);
    }
    console.error(
      `\n  Create apps/web/docs/<id>.mdx and add it to sidebars.ts.`,
    );
  }

  console.error('');
  process.exit(1);
}

console.log(
  `✓ all ${documents.length} docs pages are reachable from sidebars.ts, and every public component has one`,
);
